CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE,
    display_name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE search_providers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    connector_type VARCHAR(100) NOT NULL,
    authentication_method VARCHAR(100) NOT NULL,
    processing_pipeline JSONB NOT NULL DEFAULT '{}'::jsonb,
    provider_configuration JSONB NOT NULL DEFAULT '{}'::jsonb,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_shared BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (owner_id, name)
);

CREATE INDEX ix_search_providers_owner_active
    ON search_providers (owner_id, is_active);

CREATE INDEX ix_search_providers_shared_active
    ON search_providers (is_shared, is_active)
    WHERE is_shared = TRUE AND is_active = TRUE;

CREATE TABLE oauth_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    identity_provider VARCHAR(100) NOT NULL,
    access_token TEXT NOT NULL,
    refresh_token TEXT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (owner_id, identity_provider)
);

CREATE TABLE searches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    query VARCHAR(1024) NOT NULL,
    status VARCHAR(40) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMP WITH TIME ZONE NULL,
    completed_at TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT ck_searches_status CHECK (
        status IN (
            'PENDING',
            'RUNNING',
            'PARTIAL_RESULTS_READY',
            'FULL_RESULTS_READY',
            'FAILED',
            'CANCELLED'
        )
    )
);

CREATE INDEX ix_searches_owner_created
    ON searches (owner_id, created_at DESC);

CREATE INDEX ix_searches_created
    ON searches (created_at);

CREATE INDEX ix_searches_completed_status
    ON searches (status, completed_at)
    WHERE status IN ('FULL_RESULTS_READY', 'PARTIAL_RESULTS_READY');

CREATE TABLE search_provider_usage (
    search_id BIGINT NOT NULL REFERENCES searches (id) ON DELETE CASCADE,
    provider_id BIGINT NOT NULL REFERENCES search_providers (id) ON DELETE RESTRICT,
    provider_query VARCHAR(1024) NOT NULL,
    status VARCHAR(40) NOT NULL DEFAULT 'PENDING',
    requested_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP WITH TIME ZONE NULL,
    PRIMARY KEY (search_id, provider_id)
);

CREATE INDEX ix_search_provider_usage_provider
    ON search_provider_usage (provider_id, requested_at DESC);

CREATE TABLE search_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    search_id BIGINT NOT NULL REFERENCES searches (id) ON DELETE CASCADE,
    provider_id BIGINT NOT NULL REFERENCES search_providers (id) ON DELETE RESTRICT,
    owner_id BIGINT NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    query_text VARCHAR(1024) NOT NULL,
    title VARCHAR(500) NOT NULL,
    result_url VARCHAR(2048) NOT NULL,
    snippet VARCHAR(4000) NULL,
    retrieved INTEGER NOT NULL DEFAULT 0,
    provider_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_search_results_retrieved CHECK (retrieved >= 0)
);

CREATE INDEX ix_search_results_search_retrieved
    ON search_results (search_id, retrieved);

CREATE INDEX ix_search_results_owner_created
    ON search_results (owner_id, created_at DESC);

CREATE INDEX ix_search_results_provider
    ON search_results (provider_id);

CREATE TABLE rag_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    search_id BIGINT NOT NULL UNIQUE REFERENCES searches (id) ON DELETE CASCADE,
    owner_id BIGINT NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    model_name VARCHAR(255) NOT NULL,
    answer_text TEXT NOT NULL,
    source_metadata JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_rag_results_owner_created
    ON rag_results (owner_id, created_at DESC);
